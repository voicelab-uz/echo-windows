#!/usr/bin/env python3
"""Regenerate the offline alphabet vocabulary from pinned, licensed sources.

Run manually, never during an app build. Only data is downloaded; no upstream
code is executed. Generated Swift keeps the same data available to SwiftPM,
Xcode and the standalone swiftc regression harnesses.
"""

import csv
import hashlib
import io
from pathlib import Path
import re
import textwrap
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
UZ_REV = "74bff6bbeec7ef07eaa5cdb5c0bc7850ea967da5"
EN_REV = "20f5cc9b3f0ccc8ce45d814c532b7c2031bba31c"
UZ_URL = f"https://raw.githubusercontent.com/MaksudSharipov/UzbekLemmaStems-POS-Dataset/{UZ_REV}/"
EN_URL = f"https://raw.githubusercontent.com/dwyl/english-words/{EN_REV}/"


def download(url, checksum):
    data = urllib.request.urlopen(url, timeout=60).read()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError(f"Checksum mismatch: {url}")
    return data


def main():
    archive = download(UZ_URL + "CSV_files.zip", "dd081650eba5d3b872c9cf957ccf349fea5c38c6474d01809574ce48084b981a")
    uz_license = download(UZ_URL + "LICENSE", "c71d239df91726fc519c6eb72d318ec65820627232b2f796219e87dcf35d0ab4")
    english = download(EN_URL + "words_alpha.txt", "3ed0c94610d8bcf7c11bbb49c56aa49c7234d32b66824df91f554169e572da48")
    en_license = download(EN_URL + "LICENSE.md", "b5065838cbac452dfc855ba6e6e031481ad2c68406f70d21ead9321374653e6c")
    marks = str.maketrans({mark: "'" for mark in "ʻʼ‘’‛`´′＇"})
    uzbek = set()
    with zipfile.ZipFile(io.BytesIO(archive)) as files:
        for name in sorted(files.namelist()):
            if not name.endswith(".csv"):
                continue
            rows = csv.reader(io.StringIO(files.read(name).decode("utf-8-sig")))
            for row in rows:
                for cell in row:
                    for value in cell.split(","):
                        # Remove the dataset's morpheme boundary notation.
                        word = value.strip().lower().translate(marks).replace("/", "").replace("\\", "")
                        if re.fullmatch(r"[a-z]+(?:'[a-z]+)*'?", word) and 3 <= len(word) <= 64:
                            uzbek.add(word)
    # Protect convertible English words and shared spellings used as language
    # evidence (e.g. bank, men). No need to bundle the entire English dictionary.
    protected = {word for word in english.decode().split() if "sh" in word or "ch" in word or word in uzbek}
    output = """// Generated by scripts/generate-alphabet-lexicon.py. Do not edit by hand.
// Uzbek data: Maksud Sharipov, UzbekLemmaStems-POS-Dataset (Apache-2.0).
// English data: dwyl/english-words (Unlicense).
// Revisions, transformations and full licenses: Voicelab/Resources/AlphabetLexiconNotices.txt.

enum UzbekAlphabetLexicon {
"""
    for name, words in [("uzbek", uzbek), ("english", protected)]:
        wrapped = textwrap.wrap(" ".join(sorted(words)), width=110, break_long_words=False, break_on_hyphens=False)
        output += f'    static let {name}: Set<String> = Set("""\n'
        output += "\n".join("        " + line for line in wrapped)
        output += '\n        """.split(whereSeparator: \\.isWhitespace).map(String.init))\n\n'
    output += "}\n"
    target = ROOT / "Packages/VoiceLabCore/Sources/VoiceLabCore/Domain/UzbekAlphabetLexicon.generated.swift"
    target.write_text(output)
    notice = f"""Echo alphabet-conversion vocabulary

Uzbek stems and lemmas by Maksud Sharipov, Urgench State University.
Source: {UZ_URL}
Changes: CSV stems/lemmas merged; lowercase; apostrophes normalized; morpheme
separators removed; non-word entries and words outside 3–64 characters excluded.
{len(uzbek)} unique forms. The dataset is used for recognition, not spelling correction.

{uz_license.decode()}

English preservation vocabulary: dwyl/english-words.
Source: {EN_URL}
Changes: retained words containing sh/ch or shared with the Uzbek vocabulary
({len(protected)} forms). Shared words do not establish Uzbek language evidence.

{en_license.decode()}
"""
    (ROOT / "Voicelab/Resources/AlphabetLexiconNotices.txt").write_text(notice.rstrip() + "\n")
    print(f"Generated {len(uzbek)} Uzbek forms and {len(protected)} English protections ({len(output.encode())} bytes).")


if __name__ == "__main__":
    main()
